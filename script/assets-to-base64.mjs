// assets-to-base64.mjs
//
// Reads the 32x32 PNG icons extracted from the user's system and emits
// a single TypeScript module `src/assets.ts` that exports each PNG as
// a base64-encoded `data:image/png;base64,...` data URL. The UI
// components reference these strings in <img src> — no filesystem /
// HTTP lookup is required at runtime, and everything survives the
// ModuleLoader CJS bundling step because the strings are inlined.
//
// Run automatically BEFORE `tsdown` via the package.json `build`
// script chain so any change to the PNG files on disk is picked up.
//
// NOTE: this file lives under `script/`; paths are resolved one level
// up (..) from the script directory so the plugin root stays anchor.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url))
const PLUGIN_ROOT = resolve(SCRIPT_DIR, '..')
const ASSETS_DIR = resolve(PLUGIN_ROOT, 'assets')
const OUT_TS = resolve(PLUGIN_ROOT, 'src', 'assets.ts')

const mapping = [
  { id: 'vscode',   file: resolve(ASSETS_DIR, 'vscode.png'),   fallback: null },
  { id: 'terminal', file: resolve(ASSETS_DIR, 'cmd.png'),      fallback: null },
  { id: 'folder',   file: resolve(ASSETS_DIR, 'explorer.png'), fallback: null },
]

function pickFile(entry) {
  if (existsSync(entry.file)) return entry.file
  if (entry.fallback && existsSync(entry.fallback)) return entry.fallback
  throw new Error(`[assets-to-base64] missing icon file for ${entry.id} (tried ${entry.file}${entry.fallback ? ', ' + entry.fallback : ''})`)
}

function toDataURL(path) {
  const bytes = readFileSync(path)
  return 'data:image/png;base64,' + bytes.toString('base64')
}

const lines = [
  '// AUTO-GENERATED by assets-to-base64.mjs — do not edit by hand.',
  '// Re-run `npm run build` to regenerate.',
  '',
]
for (const entry of mapping) {
  const file = pickFile(entry)
  const url = toDataURL(file)
  lines.push(`export const ${entry.id}PngDataUrl = '${url}' as const`)
}
writeFileSync(OUT_TS, lines.join('\n') + '\n', 'utf8')
console.log(`[assets-to-base64] wrote ${OUT_TS} (${mapping.length} icons)`)
